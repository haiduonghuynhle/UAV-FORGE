#!/usr/bin/env python3
"""In-domain ceiling for the learned CAVES scorers.

Leave-one-dataset-out asks whether weights transfer between datasets. This
script asks the complementary question: with labels from the SAME dataset
(what FORGE injection provides on a deployment region), how well does a fitted
scorer rank bad accepted poses there? Each dataset is cut into K contiguous
trajectory blocks (ordered by run and frame name); each block is scored by a
model fitted on the other K-1 blocks, and AUROC is computed on the pooled
out-of-fold scores. CAVES v0 needs no fit and is scored on the same rows.

Usage (server):
    PYTHONPATH=src:scripts/reporting python3 scripts/reporting/caves_indomain_cv.py \
        --roots $RESULTS/v3_forge5050b --models lr_l2 mlp --drop-rank --caves-no-rank
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

import caves_learned_weights as clw
from uav_geolocalization.benchmark.caves import roc_auc_score


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--roots", nargs="+", required=True)
    ap.add_argument("--models", nargs="+", default=["lr_l2", "mlp"], choices=sorted(clw.MODEL_FACTORIES))
    ap.add_argument("--blocks", type=int, default=5)
    ap.add_argument("--drop-rank", action="store_true")
    ap.add_argument("--caves-no-rank", action="store_true")
    ap.add_argument("--all-frames", action="store_true")
    ap.add_argument("--out-json", type=Path)
    ap.add_argument("--out-tex", type=Path)
    args = ap.parse_args()
    clw.CAVES_NO_RANK = bool(args.caves_no_rank)
    features = [f for f in clw.LIVE_FEATURES if not (args.drop_rank and f == "retrieval_rank")]
    rows = clw.load([Path(r) for r in args.roots], accepted_only=not args.all_frames)
    by_ds = {}
    for r in rows:
        by_ds.setdefault(str(r.get("dataset")), []).append(r)
    out = {"features": features, "blocks": args.blocks, "datasets": {}}
    tex = ["% Generated by scripts/reporting/caves_indomain_cv.py; do not edit.",
           f"% roots={' '.join(args.roots)} blocks={args.blocks} drop_rank={args.drop_rank}"]
    TEX = {"vpair": "Vpair", "avl": "Avl", "uav_visloc": "Visloc"}
    from forge_mixed_confusion import caves_risk
    for ds, rs in sorted(by_ds.items()):
        rs = [r for r in rs if clw.feature_vector(r, features) is not None]
        rs = sorted(rs, key=lambda r: (str(r.get("artifact_run_dir", "")), str(r.get("image_name", ""))))
        x = np.array([clw.feature_vector(r, features) for r in rs], dtype=np.float64)
        y = np.array([int(r["_caves_label"]) for r in rs], dtype=np.int32)
        blocks = np.array_split(np.arange(len(rs)), args.blocks)
        scores = {m: np.full(len(rs), np.nan) for m in args.models}
        for b in blocks:
            te = np.zeros(len(rs), dtype=bool); te[b] = True
            tr = ~te
            if len(set(y[tr].tolist())) < 2:
                continue
            mean, scale = x[tr].mean(axis=0), x[tr].std(axis=0)
            scale[scale == 0] = 1.0
            xtr, xte = (x[tr] - mean) / scale, (x[te] - mean) / scale
            for m in args.models:
                factory = clw.MODEL_FACTORIES[m]
                try:
                    est = factory(features=features)
                except TypeError:
                    est = factory()
                est.fit(xtr, y[tr])
                scores[m][te] = est.predict_proba(xte)[:, 1]
        labels = y.tolist()
        caves = [caves_risk(r, args.caves_no_rank) if args.caves_no_rank else clw.as_float(r.get("caves_risk_score")) for r in rs]
        ok_c = [i for i, c in enumerate(caves) if c is not None and c == c]
        # Same population as the leave-one-dataset-out table: rows that carry a
        # CAVES score. Learned scorers are evaluated on exactly those rows.
        entry = {"n": len(ok_c), "bad": int(sum(labels[i] for i in ok_c)),
                 "caves": float(roc_auc_score([labels[i] for i in ok_c], [caves[i] for i in ok_c]))}
        for m in args.models:
            idx = [i for i in ok_c if not np.isnan(scores[m][i])]
            entry[m] = float(roc_auc_score([labels[i] for i in idx], [float(scores[m][i]) for i in idx])) if idx else float("nan")
        out["datasets"][ds] = entry
        print(ds, json.dumps({k: (round(v, 3) if isinstance(v, float) else v) for k, v in entry.items()}))
        t = TEX.get(ds, ds)
        tex.append(f"\\newcommand{{\\indCaves{t}}}{{{entry['caves']:.3f}}}")
        for m in args.models:
            tex.append(f"\\newcommand{{\\ind{m.replace('_', '').title()}{t}}}{{{entry[m]:.3f}}}")
    if args.out_json:
        args.out_json.write_text(json.dumps(out, indent=2))
    if args.out_tex:
        args.out_tex.write_text("\n".join(tex) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
