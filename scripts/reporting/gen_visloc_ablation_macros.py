#!/usr/bin/env python3
"""Emit macros for the matched UAV-VisLoc two-check ablation (paper Fig. 2, third panel).

Reads the six cells {fullgate,gatesoff}_{wrong_near,wrong_far,visually_similar_wrong}
of one campaign root (exactly one timestamped run per cell) and writes, per
condition and arm: attacked (treated) frames, accepted, the rate as a numeric
twin for pgfplots and as a rendered percentage, and a Wilson 95% interval.
Names are new (\\numforgeAblVisloc*, \\forgeAblVisloc*) so they cannot collide
with macros of other campaigns.
"""
from __future__ import annotations
import argparse, csv, math
from pathlib import Path

COND = {"wrong_near": "Near", "wrong_far": "Far", "visually_similar_wrong": "Sim"}
ARM = {"fullgate": "Full", "gatesoff": "Off"}

def tf(v): return str(v).strip().lower() in ("true", "1")

def wilson(k, n, z=1.96):
    if not n: return (float("nan"), float("nan"))
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)

def one_run(cell: Path) -> Path:
    hits = sorted(cell.rglob("predictions.csv"))
    if len(hits) != 1: raise SystemExit(f"{len(hits)} predictions.csv under {cell}; need exactly one")
    return hits[0]

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    lines = ["% Auto-generated by gen_visloc_ablation_macros.py - DO NOT EDIT NUMBERS BY HAND",
             f"% source: {a.root} (matched UAV-VisLoc two-check ablation, both arms on the same frames)"]
    for arm, A in ARM.items():
        for cond, C in COND.items():
            cell = a.root / f"{arm}_{cond}"
            if not (cell / ".done").exists(): raise SystemExit(f"cell not accepted (no .done): {cell}")
            rows = list(csv.DictReader(open(one_run(cell), newline="")))
            att = [r for r in rows if tf(r.get("is_adversarial")) and not str(r.get("adversarial_failure_reason") or "").strip()]
            acc = sum(tf(r.get("accepted_for_metrics")) for r in att)
            rate = acc / len(att) if att else float("nan"); lo, hi = wilson(acc, len(att))
            lines += [f"% {arm}/{cond}: {one_run(cell).parent}",
                      f"\\newcommand{{\\forgeAblVisloc{A}{C}N}}{{{len(att)}}}",
                      f"\\newcommand{{\\forgeAblVisloc{A}{C}Acc}}{{{acc}}}",
                      f"\\newcommand{{\\forgeAblVisloc{A}{C}Accept}}{{{100*rate:.1f}\\%}}",
                      f"\\newcommand{{\\numforgeAblVisloc{A}{C}}}{{{100*rate:.1f}}}",
                      f"\\newcommand{{\\numforgeAblVisloc{A}{C}Lo}}{{{100*lo:.1f}}}",
                      f"\\newcommand{{\\numforgeAblVisloc{A}{C}Hi}}{{{100*hi:.1f}}}"]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines) + "\n"); print(f"wrote {a.out} ({len(lines)} lines)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
