#!/usr/bin/env python3
"""Macros for a pre-registered held-out campaign (E1 UAV-VisLoc, E1b VPAIR).

Reads the JSON written by experiments/analysis/heldout_analysis.py and writes
one macro per number the paper cites, under a prefix (heldVisloc, heldVpair).
Cells that were not run are listed in the header, never silently dropped.

Usage:
  make_heldout_macros.py ANALYSIS.json PREFIX OUT.tex [--flights-run 09,08,03]
      [--flights-planned 09,08,03,10,05,02] [--certified-frames N]
"""
import argparse
import hashlib
import json
from pathlib import Path


def pct(x):
    return f"{100.0 * x:.1f}\\%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("analysis"); ap.add_argument("prefix"); ap.add_argument("out")
    ap.add_argument("--flights-run", default="")
    ap.add_argument("--flights-planned", default="")
    ap.add_argument("--certified-frames", type=int, default=None)
    ap.add_argument("--clean-json", default=None, help="heldout_clean_coverage.py output")
    a = ap.parse_args()
    o = json.load(open(a.analysis))
    p = o["primary"]
    trials = sum(v["trials"] for v in p["per_condition"].values())
    acc = sum(v["accepted"] for v in p["per_condition"].values())
    unsafe = sum(v["unsafe"] for v in p["per_condition"].values())
    inside = sum(v["inside_R"] for v in p["per_condition"].values())
    sha = hashlib.sha256(Path(a.analysis).read_bytes()).hexdigest()[:16]
    run = [f for f in a.flights_run.split(",") if f]
    planned = [f for f in a.flights_planned.split(",") if f]
    m = lambda k, v: f"\\newcommand{{\\{a.prefix}{k}}}{{{v}}}"
    lines = [
        "% Auto-generated by scripts/reporting/make_heldout_macros.py - DO NOT EDIT BY HAND.",
        f"% source: {Path(a.analysis).name} sha256:{sha}",
        f"% flights run: {','.join(run) or 'n/a'}; planned: {','.join(planned) or 'n/a'}; "
        f"not run: {','.join(f for f in planned if f not in run) or 'none'}",
        m("Frames", f"{p['attacked_frames']:,}".replace(",", "{,}")),
        m("FramesAccepted", p["accepted_frames"]),
        m("FrameRate", pct(p["rate"])),
        m("FrameLo", pct(p["ci"][0])),
        m("FrameHi", pct(p["ci"][1])),
        m("Trials", f"{trials:,}".replace(",", "{,}")),
        m("TrialRate", pct(acc / trials) if trials else "n/a"),
        m("Accepted", acc),
        m("Unsafe", unsafe),
        m("UnsafeShare", pct(unsafe / acc) if acc else "n/a"),
        m("InsideR", inside),
        m("NFlights", len(p["per_cluster"])),
        m("NFlightsPlanned", len(planned) if planned else len(p["per_cluster"])),
        # Hazardous acceptance: accepted and unsafe, over all fault trials.
        m("HazardRate", pct(unsafe / trials) if trials else "n/a"),
    ]
    if p.get("median_unsafe_error_m") is not None:
        lines.append(m("ErrMed", f"{p['median_unsafe_error_m']:.0f}"))
    # Flights with few attacked frames barely move the pooled rate; name them.
    small = sorted(v["n"] for v in p["per_cluster"].values() if v["n"] < 50)
    lines.append(m("NSmallFlights", len(small)))
    if small:
        lines.append(m("SmallMin", small[0]))
        lines.append(m("SmallMax", small[-1]))
    lines.append(m("NLargeFlights", len(p["per_cluster"]) - len(small)))
    # Concentration: the flight that holds the most accepted frames.
    acc_by_fl = {k: round(v["n"] * v["rate"]) for k, v in p["per_cluster"].items()}
    if len(acc_by_fl) > 1 and max(acc_by_fl.values()) > 0:
        top = max(acc_by_fl, key=lambda k: acc_by_fl[k])
        lines.append(m("TopFlight", top))
        lines.append(m("TopFlightAccepted", acc_by_fl[top]))
        lines.append(m("TopFlightRate", pct(p["per_cluster"][top]["rate"])))
    # Few-cluster sensitivity: a t-interval over the per-flight rates, which
    # treats flights (not frames) as the sampling unit.
    if len(p["per_cluster"]) > 2:
        rates = [v["rate"] for v in p["per_cluster"].values()]
        n_fl = len(rates)
        mean = sum(rates) / n_fl
        sd = (sum((r - mean) ** 2 for r in rates) / (n_fl - 1)) ** 0.5
        tcrit = {2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365}.get(n_fl - 1, 2.0)
        half = tcrit * sd / n_fl ** 0.5
        lines.append(m("TFlightLo", pct(max(0.0, mean - half))))
        lines.append(m("TFlightHi", pct(mean + half)))
    # Leave-one-flight-out frame-level rates (descriptive spread across flights).
    if len(p["per_cluster"]) > 2:
        acc = {k: round(v["n"] * v["rate"]) for k, v in p["per_cluster"].items()}
        n_all, a_all = sum(v["n"] for v in p["per_cluster"].values()), sum(acc.values())
        lofo = [(a_all - acc[k]) / (n_all - v["n"]) for k, v in p["per_cluster"].items()]
        lines.append(m("LofoMin", pct(min(lofo))))
        lines.append(m("LofoMax", pct(max(lofo))))
    if a.certified_frames:
        lines.append(m("Certified", f"{a.certified_frames:,}".replace(",", "{,}")))
        lines.append(m("Coverage", pct(p["attacked_frames"] / a.certified_frames)))
    for key, t in (o.get("per_frame_table") or {}).items():
        if key == "x1.30" and t.get("rate") is not None:
            lines.append(m("RateScaled", pct(t["rate"])))
        if key == "x1.15" and t.get("rate") is not None:
            lines.append(m("RateScaledLow", pct(t["rate"])))
    if a.clean_json:
        c = json.load(open(a.clean_json))["total"]
        lines.append(f"% clean controls: {Path(a.clean_json).name} "
                     f"sha256:{hashlib.sha256(Path(a.clean_json).read_bytes()).hexdigest()[:16]}")
        fl = sorted(json.load(open(a.clean_json)).get("flights", {}), key=lambda f: run.index(f) if f in run else 99)
        lines.append(m("CleanNFlights", len(fl)))
        lines.append(m("CleanFrames", f"{c['frames']:,}".replace(",", "{,}")))
        lines.append(m("CleanAccept", pct(c["accepted"] / c["frames"])))
        lines.append(m("CleanUnsafe", pct(c["unsafe"] / c["frames"])))
        # Coverage on the frames that carry a footprint bound, the population
        # the attack rate is measured on (selection check).
        if c.get("cert"):
            lines.append(m("CleanCertAccept", pct(c["cert_accepted"] / c["cert"])))
    Path(a.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
