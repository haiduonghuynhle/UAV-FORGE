#!/usr/bin/env python3
"""Our acceptance gate against common single-rule gates, on the same frames.

Common rules (inlier count >= T, inlier ratio >= r) are replayed on the mixed
50/50 runs that carry only the sanity checks (the two proposed checks removed),
because those runs still solve the frames our gate would refuse. Our gate is
read from the full-gate runs on the same frames. A frame counts under the
reference it actually received (is_wrong_reference); 'kept' is the share of
correct-reference frames accepted, 'leak' the share of wrong-reference frames
accepted. Frames the injector failed closed on are excluded from both runs.

Usage (server):
    python3 scripts/reporting/gate_rule_replay.py --full $RESULTS/v3_forge5050b \
        --off $RESULTS/v3_forge5050b_gatesoff --datasets vpair avl uav_visloc \
        --out-tex gate_rules_macros.tex
"""
from __future__ import annotations

import argparse
import csv
import glob
from pathlib import Path

TEX = {"vpair": "Vpair", "avl": "Avl", "uav_visloc": "Visloc"}
RULES = [
    ("Sanity", "sanity checks only", lambda r: True),
    ("InlTwenty", "inliers >= 20", lambda r: _f(r["num_inliers"]) >= 20),
    ("InlFifty", "inliers >= 50", lambda r: _f(r["num_inliers"]) >= 50),
    ("InlHundred", "inliers >= 100", lambda r: _f(r["num_inliers"]) >= 100),
    ("RatioHalf", "inlier ratio >= 0.5", lambda r: _f(r["inlier_ratio"]) >= 0.5),
]


def _f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def load(root: str, ds: str, cells=None):
    """Rows of every finished cell of `ds` under root; `cells` restricts to a
    set of condition directory names so both roots cover the same frames."""
    rows = []
    for p in glob.glob(f"{root}/{ds}_*/*/*/*/predictions.csv"):
        cell = p.split("/")[-5]
        if cells is not None and cell not in cells:
            continue
        for r in csv.DictReader(open(p, encoding="utf-8")):
            if r.get("reference_image_missing", "False") == "True":
                continue
            if r.get("is_wrong_reference") not in ("True", "False"):
                continue
            r["_cell"] = cell
            rows.append(r)
    return rows


def cells_of(root: str, ds: str):
    return {p.split("/")[-5] for p in glob.glob(f"{root}/{ds}_*/*/*/*/predictions.csv")}


def kept_leak(rows, accept):
    ca = cr = wa = wr = 0
    for r in rows:
        a = bool(accept(r))
        if r["is_wrong_reference"] == "True":
            wa += a; wr += (not a)
        else:
            ca += a; cr += (not a)
    return ca / max(1, ca + cr), wa / max(1, wa + wr), ca + cr, wa + wr


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--full", required=True)
    ap.add_argument("--off", required=True)
    ap.add_argument("--datasets", nargs="+", default=["vpair", "avl", "uav_visloc"])
    ap.add_argument("--out-tex", type=Path)
    args = ap.parse_args()
    base = lambda r: r["accepted_for_metrics"] == "True"
    lines = ["% Generated by scripts/reporting/gate_rule_replay.py; do not edit.",
             f"% full={args.full} off={args.off}"]
    for ds in args.datasets:
        common = cells_of(args.full, ds) & cells_of(args.off, ds)
        full, off = load(args.full, ds, common), load(args.off, ds, common)
        if not full or not off:
            print(f"{ds}: missing runs (full={len(full)} off={len(off)}), skipped"); continue
        print(f"{ds}: cells used = {sorted(common)}")
        lines.append(f"% {ds}: cells {sorted(common)}")
        t = TEX[ds]
        k, l, nc, nw = kept_leak(full, base)
        print(f"== {ds}: correct n={nc} wrong n={nw}")
        print(f"  {'our gate (full run)':24s} kept {100*k:5.1f}%  leak {100*l:5.1f}%")
        lines += [f"\\newcommand{{\\grOurs{t}Kept}}{{{100*k:.1f}\\%}}", f"\\newcommand{{\\grOurs{t}Leak}}{{{100*l:.1f}\\%}}",
                  f"\\newcommand{{\\grnumOurs{t}Kept}}{{{100*k:.1f}}}", f"\\newcommand{{\\grnumOurs{t}Leak}}{{{100*l:.1f}}}",
                  f"\\newcommand{{\\grN{t}Correct}}{{{nc}}}", f"\\newcommand{{\\grN{t}Wrong}}{{{nw}}}"]
        # Coverage-matched inlier gate: the largest threshold (fine grid) whose
        # kept share is at least ours; the most favourable threshold the single
        # rule can be given on this dataset, chosen with hindsight.
        k_ours = k
        match = None
        for T in range(5, 201, 5):
            km, lm, _, _ = kept_leak(off, lambda r, T=T: base(r) and _f(r["num_inliers"]) >= T)
            if km >= k_ours:
                match = (T, km, lm)
        if match:
            T, km, lm = match
            print(f"  {'inliers >= T, coverage-matched':24s} T={T} kept {100*km:5.1f}%  leak {100*lm:5.1f}%")
            lines += [f"\\newcommand{{\\grMatch{t}T}}{{{T}}}",
                      f"\\newcommand{{\\grMatch{t}Kept}}{{{100*km:.1f}\\%}}", f"\\newcommand{{\\grMatch{t}Leak}}{{{100*lm:.1f}\\%}}",
                      f"\\newcommand{{\\grnumMatch{t}Kept}}{{{100*km:.1f}}}", f"\\newcommand{{\\grnumMatch{t}Leak}}{{{100*lm:.1f}}}"]
        for key, label, rule in RULES:
            k, l, _, _ = kept_leak(off, lambda r, rule=rule: base(r) and rule(r))
            print(f"  {label:24s} kept {100*k:5.1f}%  leak {100*l:5.1f}%")
            lines += [f"\\newcommand{{\\gr{key}{t}Kept}}{{{100*k:.1f}\\%}}", f"\\newcommand{{\\gr{key}{t}Leak}}{{{100*l:.1f}\\%}}",
                      f"\\newcommand{{\\grnum{key}{t}Kept}}{{{100*k:.1f}}}", f"\\newcommand{{\\grnum{key}{t}Leak}}{{{100*l:.1f}}}"]
    if args.out_tex:
        args.out_tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote", args.out_tex)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
