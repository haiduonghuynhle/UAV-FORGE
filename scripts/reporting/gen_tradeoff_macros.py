#!/usr/bin/env python3
"""Clean-control rows of the acceptance-layer trade-off table, from records.

For each dataset and acceptance-layer state, the clean (no-injection) run is
read on the frames that the corresponding injection cell attacked, exactly as
the generated per-dataset FORGE tables pair their clean control rows. Emits
coverage (accepted share), unsafe share (accepted and error beyond R) and the
frame count: \\toCov{Ds}{Full|Off|Wrap}, \\toUnsafe..., \\toN...
"""
from __future__ import annotations
import argparse, csv, sys
from pathlib import Path
_R = Path(__file__).resolve().parent
sys.path.insert(0, str(_R))
import gen_v3_tables as gen  # noqa: E402

V3 = Path("/workspace/forge/results/v3")
# (clean run dir, injection cell dir giving the attacked frames)
CELLS = {
    ("avl", "Full"): ("avl_ours_ultravpr/avl/ours_ultravpr_cascade_6dof_e2e/20260803_050832",
                      "forgec_avl_wrong_near/avl/ours_ultravpr_cascade_6dof_e2e/20260805_195057"),
    ("avl", "Off"): ("gatesoff_avl_clean/avl/ours_ultravpr_cascade_6dof_e2e/20260814_110428",
                     "forge_gatesoff_avl_wrong_near/avl/ours_ultravpr_cascade_6dof_e2e/20260814_115125"),
    ("avl", "Wrap"): ("avl_wrapper_k1/avl/ultravpr_roma_homography_wrapper_e2e/20260813_105138",
                      "forgeb_wrapper_avl_wrong_near/avl/ultravpr_roma_homography_wrapper_e2e/20260813_120059"),
    ("vpair", "Full"): ("vpair_ours_ultravpr/vpair/ours_ultravpr_cascade_6dof_e2e/20260803_042050",
                        "forgec_vpair_wrong_near/vpair/ours_ultravpr_cascade_6dof_e2e/20260810_155044"),
    ("vpair", "Off"): ("gatesoff_vpair_clean/vpair/ours_ultravpr_cascade_6dof_e2e/20260813_233636",
                       "forge_gatesoff_vpair_wrong_near/vpair/ours_ultravpr_cascade_6dof_e2e/20260813_152910"),
    ("vpair", "Wrap"): (None, "forgeb_wrapper_vpair_wrong_near/vpair/ultravpr_roma_homography_wrapper_e2e/20260805_150321"),
    ("uav_visloc", "Full"): ("visloc_ours_ultravpr/uav_visloc/ours_ultravpr_cascade_6dof_e2e/20260810_232532",
                             "forgeb_visloc_wrong_near/uav_visloc/ours_ultravpr_cascade_6dof_e2e/20260811_044051"),
    # The UAV-VisLoc gates-off arm is a matched pair on one flight, so it needs
    # its own clean control and its own full-gate baseline on the same frames.
    # Reading it against the full-campaign row would compare two populations.
    ("uav_visloc", "Off"): ("gatesoff_visloc_clean/uav_visloc/ours_ultravpr_cascade_6dof_e2e/20260829_044424",
                            "../v3_visloc_ablation_b/gatesoff_wrong_near/uav_visloc/ours_ultravpr_cascade_6dof_e2e/20260822_224915"),
    # OffBase must come from a clean run that built the SAME reference corpus as
    # the ablation arms (uav_corpus_ref_flight_hash d6b4c13f, flight 01 alone).
    # visloc_ours_ultravpr looks identical in pipeline_config but ran without a
    # sample cap, so it spans flights 01/04/11 and builds a different corpus;
    # pairing it here compared two retrieval shortlists, not two gate settings.
    ("uav_visloc", "OffBase"): ("fullgate_visloc_clean/uav_visloc/ours_ultravpr_cascade_6dof_e2e/20260830_050216",
                                "../v3_visloc_ablation_b/gatesoff_wrong_near/uav_visloc/ours_ultravpr_cascade_6dof_e2e/20260822_224915"),
}
DS = {"avl": "Avl", "vpair": "Vpair", "uav_visloc": "Visloc"}

def thousands(n):
    # LaTeX thousands separator, so the table never needs a hand edit
    return f"{n:,}".replace(",", "{,}")

def tf(v): return str(v).strip().lower() in ("true", "1")
def fl(v):
    try: return float(v)
    except (TypeError, ValueError): return float("nan")
def rows(p): return list(csv.DictReader(open(p, newline="")))
def attacked_names(p):
    # One definition of the injected population: gen_v3_tables._attacked_rows
    # (also drops frames with no parsable anchor or ground truth), so this
    # table cannot disagree with the stratified table about the frame count.
    from gen_v3_tables import _attacked_rows
    return {r["image_name"] for r in _attacked_rows(str(p.parent))}

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--v3", type=Path, default=V3)
    ap.add_argument("--vpair-wrapper-clean", type=Path, help="clean wrapper run on VPAIR (k5), read from the thesis table source comment")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    lines = ["% Auto-generated by gen_tradeoff_macros.py - DO NOT EDIT NUMBERS BY HAND",
             "% clean control runs read on the attacked frames of the paired injection cell"]
    for (ds, state), (clean_rel, inj_rel) in CELLS.items():
        clean = a.v3 / clean_rel / "predictions.csv" if clean_rel else a.vpair_wrapper_clean
        if clean is None or not Path(clean).exists():
            lines.append(f"% {ds}/{state}: clean run missing ({clean}); macros not emitted"); continue
        names = attacked_names(a.v3 / inj_rel / "predictions.csv")
        sub = [r for r in rows(clean) if r["image_name"] in names]
        R = gen.DEFAULT_RADIUS_M[ds]
        acc = [r for r in sub if tf(r["accepted_for_metrics"])]
        uns = [r for r in acc if fl(r["post_fgo_error_m"]) > R]
        key = DS[ds] + state
        lines += [f"% source: {clean} paired to {len(sub)} attacked frames of {a.v3 / inj_rel}",
                  f"\\newcommand{{\\toN{key}}}{{{thousands(len(sub))}}}",
                  f"\\newcommand{{\\toCov{key}}}{{{100*len(acc)/len(sub):.1f}\\%}}",
                  f"\\newcommand{{\\toUnsafe{key}}}{{{100*len(uns)/len(sub):.1f}\\%}}"]
    a.out.write_text("\n".join(lines) + "\n"); print(f"wrote {a.out}")

if __name__ == "__main__":
    main()
