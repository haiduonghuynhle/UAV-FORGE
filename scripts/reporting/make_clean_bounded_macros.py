#!/usr/bin/env python3
"""Clean-run wrong-tile share on the development frames that carry a measured
footprint, under the measured label and under the fitted one.

Sec. V-A reports how often the clean pipeline selects a tile disjoint from the
camera footprint. On UAV-VisLoc that share was computed with the fitted
half-extent of the development runs. This script recomputes it on the frames
whose footprint was later measured (E5b, footprint_<flight>.csv, status OK),
with the same per-axis rule as experiments/analysis/heldout_analysis.py
(disjoint_under: either axis beyond reference half-extent + query bound +
slack), the per-map reference half-extents, and, for comparison, the fitted
constant on the same frames. It also counts accepted clean fixes whose selected
tile is disjoint under the measured label.

Usage:
    python3 scripts/reporting/make_clean_bounded_macros.py \
        --clean $RESULTS/v3/visloc_ours_ultravpr/uav_visloc/ours_ultravpr_cascade_6dof_e2e/20260810_232532 \
        --footprints results_server/v4_2026-10-24/analysis_out/footprint_01.csv ... \
        --per-map results_server/v4_2026-10-24/analysis_out/per_map_half_m.json \
        --out Report/Paper/aicap-2027/tables/clean_bounded_numbers.tex
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path

SLACK_M = 15.0                     # FORGE_FOOTPRINT_SLACK_M, tables/protocol_constants.tex
FITTED_QUERY_HALF_M = 101.0        # \protoQueryHalfVisloc
FITTED_REF_HALF_M = (254.0, 305.8) # gen_v3_tables.REF_HALF_M["uav_visloc"]


import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_v3_tables as G  # noqa: E402  (same metres-per-axis and anchor parsing as the tables of record)


def per_axis_m(lat1: float, lon1: float, lat2: float, lon2: float) -> tuple[float, float]:
    return G._per_axis_m(lat1, lon1, lat2, lon2)


def disjoint_under(de: float, dn: float, ref_half: tuple[float, float], q_half: float) -> bool:
    return de > ref_half[0] + q_half + SLACK_M or dn > ref_half[1] + q_half + SLACK_M


def anchor(r: dict) -> dict | None:
    ll = G._anchor_latlon(r)
    return None if ll is None else {"lat": ll[0], "lon": ll[1]}


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:16]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--clean", required=True, type=Path, help="clean run directory of record")
    ap.add_argument("--footprints", required=True, nargs="+", type=Path)
    ap.add_argument("--per-map", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()

    bound: dict[str, float] = {}
    for p in a.footprints:
        for r in csv.DictReader(p.open(newline="", encoding="utf-8")):
            if r["status"] == "OK" and r["query_half_bound_m"]:
                bound[r["image_name"]] = float(r["query_half_bound_m"])
    per_map = {k: tuple(v) for k, v in json.loads(a.per_map.read_text()).items()}
    pred = a.clean / "predictions.csv"
    rows = list(csv.DictReader(pred.open(newline="", encoding="utf-8")))

    n_all = wrong_fit_all = 0
    n_b = wrong_meas = wrong_fit = acc_b = 0
    acc_wrong_errs: list[float] = []
    for r in rows:
        an = anchor(r)
        if an is None:
            continue
        gt_lat, gt_lon = float(r["gt_lat"]), float(r["gt_lon"])
        de, dn = per_axis_m(gt_lat, gt_lon, float(an["lat"]), float(an["lon"]))
        wf = disjoint_under(de, dn, FITTED_REF_HALF_M, FITTED_QUERY_HALF_M)
        n_all += 1
        wrong_fit_all += wf
        name = r["image_name"]
        if name not in bound:
            continue
        n_b += 1
        wm = disjoint_under(de, dn, per_map[name.split("/")[0]], bound[name])
        wrong_meas += wm
        wrong_fit += wf
        if r.get("accepted_for_metrics") == "True":
            acc_b += 1
            if wm:
                acc_wrong_errs.append(float(r["post_fgo_error_m"]))

    lines = [
        "% Auto-generated by scripts/reporting/make_clean_bounded_macros.py - DO NOT EDIT BY HAND.",
        f"% source clean run: {pred} sha256:{sha(pred)}",
        f"% source per-map reference half-extents: {a.per_map} sha256:{sha(a.per_map)}",
    ]
    lines += [f"% source footprint table: {p} sha256:{sha(p)}" for p in a.footprints]
    lines += [
        f"\\newcommand{{\\cbAllFrames}}{{{n_all:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cbAllWrongFittedPct}}{{{100.0 * wrong_fit_all / n_all:.1f}\\%}}",
        f"\\newcommand{{\\cbFrames}}{{{n_b}}}",
        f"\\newcommand{{\\cbWrongMeasured}}{{{wrong_meas}}}",
        f"\\newcommand{{\\cbWrongMeasuredPct}}{{{100.0 * wrong_meas / n_b:.1f}\\%}}",
        f"\\newcommand{{\\cbWrongFitted}}{{{wrong_fit}}}",
        f"\\newcommand{{\\cbWrongFittedPct}}{{{100.0 * wrong_fit / n_b:.1f}\\%}}",
        f"\\newcommand{{\\cbAccepted}}{{{acc_b}}}",
        f"\\newcommand{{\\cbAcceptedWrong}}{{{len(acc_wrong_errs)}}}",
    ]
    if acc_wrong_errs:
        lines.append(f"\\newcommand{{\\cbAcceptedWrongErrMax}}{{{max(acc_wrong_errs):.0f}}}")
    a.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {a.out}")
    print("\n".join(l for l in lines if l.startswith("\\newcommand")))


if __name__ == "__main__":
    main()
