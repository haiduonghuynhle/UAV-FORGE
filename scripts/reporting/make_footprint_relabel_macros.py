#!/usr/bin/env python3
"""Macros for the outcome-free footprint relabel of the UAV-VisLoc campaign.

The camera half-extent of the cells of record is a constant fitted on the
same flights. E5b measures each frame's ground footprint instead, from its
ground sampling distance against the next frames (GT displacement over
matched pixel displacement), which uses no localization outcome. This script
turns the relabel computed by experiments/analysis/heldout_analysis.py
(--query-table) and the E5b summary into the macros the paper cites.

Usage:
  make_footprint_relabel_macros.py RELABEL.json E5B_SUMMARY.json OUT.tex
"""
import hashlib
import json
import sys
from pathlib import Path

DEV_FLIGHTS = ("01", "04", "11")


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()[:16]


def pct(x):
    return f"{100.0 * x:.1f}\\%"


def main(relabel_path, summary_path, out_path):
    rel = json.load(open(relabel_path))
    flights = json.load(open(summary_path))["flights"]
    prim = rel["primary"]
    cert = rel["per_frame_table"]["x1.00"]
    hi = rel["per_frame_table"]["x1.30"]
    split = rel["per_frame_table_split"]
    near = split["wrong_near"]
    inside_disjoint = sum(c["bound_disjoint"]["accepted_inside_R"] for c in split.values())
    inside_all = sum(v["accepted_inside_R"] for c in split.values() for v in c.values())
    medians = [flights[f]["bound_median_m"] for f in DEV_FLIGHTS]
    lines = [
        "% Auto-generated by scripts/reporting/make_footprint_relabel_macros.py - DO NOT EDIT BY HAND.",
        "% Outcome-free relabel of the UAV-VisLoc cells with the E5b per-frame footprint bound.",
        f"% source relabel: {Path(relabel_path).name} sha256:{sha(relabel_path)}",
        f"% source e5b:     {Path(summary_path).name} sha256:{sha(summary_path)}",
        f"\\newcommand{{\\fpAllFrames}}{{{sum(flights[f]['frames'] for f in DEV_FLIGHTS):,}}}",
        f"\\newcommand{{\\fpCertFrames}}{{{sum(flights[f]['ok'] for f in DEV_FLIGHTS)}}}",
        f"\\newcommand{{\\fpBoundLo}}{{{int(min(medians) + 0.5)}}}",
        f"\\newcommand{{\\fpBoundHi}}{{{int(max(medians) + 0.5)}}}",
        f"\\newcommand{{\\fpCertNear}}{{{near['bound_overlap']['trials'] + near['bound_disjoint']['trials']}}}",
        f"\\newcommand{{\\fpOverlapNear}}{{{near['bound_overlap']['trials']}}}",
        f"\\newcommand{{\\fpAttackedBase}}{{{prim['attacked_frames']:,}}}",
        f"\\newcommand{{\\fpKept}}{{{cert['attacked_frames']}}}",
        f"\\newcommand{{\\fpKeptAccepted}}{{{cert['accepted_frames']}}}",
        f"\\newcommand{{\\fpRate}}{{{pct(cert['rate'])}}}",
        f"\\newcommand{{\\fpLo}}{{{pct(cert['ci'][0])}}}",
        f"\\newcommand{{\\fpHi}}{{{pct(cert['ci'][1])}}}",
        f"\\newcommand{{\\fpRateScaled}}{{{pct(hi['rate'])}}}",
        f"\\newcommand{{\\fpInsideRAll}}{{{inside_all}}}",
        f"\\newcommand{{\\fpInsideRDisjoint}}{{{inside_disjoint}}}",
        f"\\newcommand{{\\fpKeptTopFlight}}{{{max(v['n'] for v in cert['per_cluster'].values())}}}",
    ]
    Path(out_path).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main(*sys.argv[1:4])
