#!/usr/bin/env python3
"""Pooled forced-reference acceptance of the ungated wrapper (Table IV).

Table IV prints the wrapper's acceptance per condition from v3_numbers.tex.
This script pools the same three record cells per dataset with the same
population rules (gen_v3_tables._attacked_rows, and _is_genuine_fault so that
AnyVisLoc counts only tiles disjoint under the footprint selected by
FORGE_AVL_FOOTPRINT). It first recomputes each per-condition rate and refuses
to write anything unless they match the printed macros.

Usage:
    FORGE_AVL_FOOTPRINT=oblique python3 scripts/reporting/make_wrapper_pooled_macros.py \
        --root $RESULTS/v3 \
        --macros Report/Paper/aicap-2027/tables/v3_numbers.tex \
        --out Report/Paper/aicap-2027/tables/wrapper_pooled_numbers.tex
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_v3_tables as G  # noqa: E402

CELLS = {
    "vpair": ("Vpair", {
        "Near": "forgeb_wrapper_vpair_wrong_near/vpair/ultravpr_roma_homography_wrapper_e2e/20260805_150321",
        "Far": "forgeb_wrapper_vpair_wrong_far/vpair/ultravpr_roma_homography_wrapper_e2e/20260805_164902",
        "Sim": "forgeb_wrapper_vpair_visually_similar_wrong/vpair/ultravpr_roma_homography_wrapper_e2e/20260805_175138"}),
    "avl": ("Avl", {
        "Near": "forgeb_wrapper_avl_wrong_near/avl/ultravpr_roma_homography_wrapper_e2e/20260813_120059",
        "Far": "forgeb_wrapper_avl_wrong_far/avl/ultravpr_roma_homography_wrapper_e2e/20260813_130855",
        "Sim": "forgeb_wrapper_avl_visually_similar_wrong/avl/ultravpr_roma_homography_wrapper_e2e/20260813_141558"}),
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, type=Path)
    ap.add_argument("--macros", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()
    printed = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", a.macros.read_text()))
    lines = ["% Auto-generated by scripts/reporting/make_wrapper_pooled_macros.py - DO NOT EDIT BY HAND."]
    for ds, (tag, cells) in CELLS.items():
        acc = n = 0
        for cond, rel in cells.items():
            rows = [r for r in G._attacked_rows(str(a.root / rel)) if G._is_genuine_fault(r, ds)]
            k = sum(r.get("accepted_for_metrics") == "True" for r in rows)
            rate = f"{100.0 * k / len(rows):.1f}\\%"
            key = f"forgeWrap{'Avl' if ds == 'avl' else ''}{cond}Accept"
            if printed.get(key) != rate:
                raise SystemExit(f"{key}: recomputed {rate}, printed {printed.get(key)}; refusing to pool")
            lines.append(f"% source: {a.root / rel} accepted {k}/{len(rows)} (matches \\{key})")
            acc += k
            n += len(rows)
        lines.append(f"\\newcommand{{\\wpN{tag}}}{{{n:,}}}".replace(",", "{,}"))
        lines.append(f"\\newcommand{{\\wpRate{tag}}}{{{100.0 * acc / n:.1f}\\%}}")
    a.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {a.out}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
