#!/usr/bin/env python3
"""Percentage-point twins of difference macros.

forge_block_ci.py prints paired differences with a percent sign. A
difference of two rates is in percentage points, so this script copies each
named macro from a generated file and writes a twin, suffixed Pts, with the
same digits and no percent sign. It never computes a value.

Usage: make_points_macros.py SRC.tex OUT.tex NAME [NAME ...]
"""
import hashlib
import re
import sys
from pathlib import Path


def main(src, out, names):
    text = Path(src).read_text()
    lines = ["% Auto-generated by scripts/reporting/make_points_macros.py - DO NOT EDIT BY HAND.",
             f"% source: {Path(src).name} sha256:{hashlib.sha256(text.encode()).hexdigest()[:16]}"]
    for name in names:
        m = re.search(r"\\newcommand\{\\" + name + r"\}\{([^}]*)\}", text)
        if not m:
            raise SystemExit(f"macro {name} not found in {src}")
        val = m.group(1)
        if not val.endswith("\\%"):
            raise SystemExit(f"macro {name} has no percent sign: {val}")
        lines.append(f"\\newcommand{{\\{name}Pts}}{{{val[:-2]}}}")
    Path(out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines[2:]))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
