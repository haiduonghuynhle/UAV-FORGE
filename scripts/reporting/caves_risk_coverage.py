#!/usr/bin/env python3
"""Risk-coverage curves for the CAVES score, from the LODO fit of record.

AUROC ranks pairs; it says nothing about the risk a deployment carries at a
chosen coverage. Jaeger et al. and Traub et al. argue that failure detectors
must be read on the risk-coverage plane instead. This script reads the
per-observation scores dumped by ``caves_learned_weights.py`` and reports
AURC (selective risk) and AUGRC (generalized risk) with block bootstrap
intervals, so no refit can move the numbers away from the published AUROCs.

Usage:
  python3 scripts/reporting/caves_risk_coverage.py \
      --lodo-json <dir>/caves_learned_weights.json \
      --draws 2000 --out <paper>/tables/risk_coverage_numbers.tex
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

DATASET_KEY = {"avl": "Avl", "vpair": "Vpair", "uav_visloc": "Visloc"}


def curve(scores: Sequence[float], labels: Sequence[int]) -> Tuple[float, float]:
    """AURC and AUGRC. Low score = confident safe, so retain low scores first."""
    n = len(scores)
    order = sorted(range(n), key=lambda i: scores[i])
    bad = 0
    aurc = augrc = 0.0
    for k, i in enumerate(order, start=1):
        bad += labels[i]
        aurc += bad / k
        augrc += bad / n
    return aurc / n, augrc / n


def references(labels: Sequence[int]) -> Dict[str, float]:
    """Random and oracle AURC at the observed prevalence."""
    n = len(labels)
    n_bad = sum(labels)
    n_good = n - n_bad
    p = n_bad / n
    opt = sum((k - n_good) / k for k in range(n_good + 1, n + 1)) / n
    return {"random_aurc": p, "oracle_aurc": opt,
            "random_augrc": p * (n + 1) / (2 * n)}


def blocks_of(groups: Sequence[str]) -> List[List[int]]:
    """Contiguous runs of the same group id, as index lists."""
    out: List[List[int]] = []
    for i, g in enumerate(groups):
        if out and groups[i - 1] == g:
            out[-1].append(i)
        else:
            out.append([i])
    return out


def ci(scores: Sequence[float], labels: Sequence[int], groups: Sequence[str],
       draws: int, seed: int = 7) -> Dict[str, Tuple[float, float]]:
    blocks = blocks_of(groups)
    rng = random.Random(seed)
    aurcs: List[float] = []
    augrcs: List[float] = []
    for _ in range(draws):
        idx: List[int] = []
        while len(idx) < len(scores):
            idx.extend(rng.choice(blocks))
        idx = idx[:len(scores)]
        s = [scores[i] for i in idx]
        y = [labels[i] for i in idx]
        if 0 < sum(y) < len(y):
            a, g = curve(s, y)
            aurcs.append(a)
            augrcs.append(g)
    def pct(v: List[float]) -> Tuple[float, float]:
        v = sorted(v)
        return v[int(0.025 * len(v))], v[int(0.975 * len(v)) - 1]
    return {"aurc": pct(aurcs), "augrc": pct(augrcs)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lodo-json", type=Path, required=True)
    ap.add_argument("--draws", type=int, default=2000)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--json-out", type=Path)
    args = ap.parse_args()

    data = json.loads(args.lodo_json.read_text())
    report: Dict[str, Dict[str, float]] = {}
    for dataset, fold in sorted(data["folds"].items()):
        if fold.get("status") != "ok":
            continue
        missing = [k for k in ("caves_scores", "labels", "blocks") if k not in fold]
        if missing:
            raise SystemExit(f"{dataset}: fold lacks {missing}; rerun caves_learned_weights.py")
        s, y, g = fold["caves_scores"], fold["labels"], fold["blocks"]
        if not (len(s) == len(y) == len(g)):
            raise SystemExit(f"{dataset}: score/label/block lengths differ")
        aurc, augrc = curve(s, y)
        bounds = ci(s, y, g, args.draws)
        report[dataset] = {
            "n": len(y), "n_bad": sum(y), "auroc": fold["caves_auroc"],
            "aurc": aurc, "aurc_lo": bounds["aurc"][0], "aurc_hi": bounds["aurc"][1],
            "augrc": augrc, "augrc_lo": bounds["augrc"][0], "augrc_hi": bounds["augrc"][1],
            **references(y),
        }
        r = report[dataset]
        print(f"{dataset:<12} n={r['n']:>5} bad={r['n_bad']:>4} AUROC={r['auroc']:.3f}  "
              f"AURC={aurc:.3f} [{r['aurc_lo']:.3f}, {r['aurc_hi']:.3f}]  "
              f"random={r['random_aurc']:.3f} oracle={r['oracle_aurc']:.3f}  "
              f"AUGRC={augrc:.3f} [{r['augrc_lo']:.3f}, {r['augrc_hi']:.3f}]")

    if args.json_out:
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(json.dumps(report, indent=2))
    if args.out:
        lines = ["% Generated by scripts/reporting/caves_risk_coverage.py",
                 f"% source: {args.lodo_json} (LODO fit of record, block bootstrap"
                 f" {args.draws} draws, seed 7)"]
        for dataset, r in report.items():
            k = DATASET_KEY[dataset]
            for name, val in (("Aurc", r["aurc"]), ("AurcLo", r["aurc_lo"]),
                              ("AurcHi", r["aurc_hi"]), ("AurcRand", r["random_aurc"]),
                              ("AurcOracle", r["oracle_aurc"]), ("Augrc", r["augrc"]),
                              ("AugrcLo", r["augrc_lo"]), ("AugrcHi", r["augrc_hi"]),
                              ("AugrcRand", r["random_augrc"])):
                lines.append(f"\\newcommand{{\\rc{name}{k}}}{{{val:.3f}}}")
        args.out.write_text("\n".join(lines) + "\n")
        print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
