#!/usr/bin/env python3
"""How much do the hand-set CAVES weights matter?

Scores the accepted poses of the given FORGE cells with (a) the published
weights, (b) every weight set to one, and (c) random perturbations of the
published weights (each multiplied by an independent factor in [lo, hi]).
Reports AUROC against bad_pose_label per dataset. If (a) sits inside the
spread of (c) and close to (b), the particular numbers carry little of the
ranking; the signals and their assumed directions do.

Usage (server):
    PYTHONPATH=src python3 scripts/reporting/caves_weight_sensitivity.py \
        --roots /workspace/forge/results/v3_forge5050b --drop-rank \
        --out-json sens.json --out-tex caves_sens_macros.tex
"""
from __future__ import annotations

import argparse
import csv
import glob
import json
import random
from pathlib import Path

from uav_geolocalization.benchmark import caves as C

DATASETS = ("vpair", "avl", "uav_visloc")
TEX = {"vpair": "Vpair", "avl": "Avl", "uav_visloc": "Visloc"}


def accepted_rows(root: str, ds: str):
    out = []
    for p in glob.glob(f"{root}/{ds}_*/*/*/*/predictions.csv"):
        for r in csv.DictReader(open(p, encoding="utf-8")):
            if r.get("accepted_for_metrics") == "True" and r.get("bad_pose_label") in ("True", "False"):
                out.append(r)
    return out


def auroc(weights, rows):
    C._caves_v0_weight = lambda n: weights[n]  # the scorer reads weights through this hook
    scores = [C.compute_caves_v0(r).risk_score for r in rows]
    labels = [1 if r["bad_pose_label"] == "True" else 0 for r in rows]
    return C.roc_auc_score(labels, scores)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--roots", nargs="+", required=True)
    ap.add_argument("--draws", type=int, default=200)
    ap.add_argument("--lo", type=float, default=0.5)
    ap.add_argument("--hi", type=float, default=2.0)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--drop-rank", action="store_true",
                    help="zero the retrieval-rank weight (injection fingerprints rank)")
    ap.add_argument("--out-json", type=Path)
    ap.add_argument("--out-tex", type=Path)
    args = ap.parse_args()

    names = [s.name for s in C.CAVES_V0_COMPONENT_SPECS]
    base = {n: C.CAVES_V0_COMPONENT_BY_NAME[n].weight for n in names}
    if args.drop_rank:
        base["late_retrieval_rank"] = 0.0
    rng = random.Random(args.seed)
    result = {"roots": args.roots, "draws": args.draws, "range": [args.lo, args.hi],
              "drop_rank": args.drop_rank, "datasets": {}}
    for ds in DATASETS:
        rows = [r for root in args.roots for r in accepted_rows(root, ds)]
        if not rows:
            continue
        pub = auroc(base, rows)
        uni = auroc({n: (0.0 if base[n] == 0.0 else 1.0) for n in names}, rows)
        draws = sorted(
            auroc({n: base[n] * rng.uniform(args.lo, args.hi) for n in names}, rows)
            for _ in range(args.draws)
        )
        k = len(draws)
        result["datasets"][ds] = {
            "n": len(rows), "bad": sum(r["bad_pose_label"] == "True" for r in rows),
            "published": pub, "uniform": uni,
            "random_min": draws[0], "random_p05": draws[int(0.05 * k)],
            "random_median": draws[k // 2], "random_p95": draws[int(0.95 * k) - 1],
            "random_max": draws[-1],
            "published_percentile": sum(d <= pub for d in draws) / k,
        }
        d = result["datasets"][ds]
        print(f"{ds:11s} n={d['n']} bad={d['bad']} published={pub:.3f} uniform={uni:.3f} "
              f"random median={d['random_median']:.3f} [{d['random_min']:.3f}, {d['random_max']:.3f}] "
              f"published at percentile {100 * d['published_percentile']:.0f}")
    if args.out_json:
        args.out_json.write_text(json.dumps(result, indent=2))
    if args.out_tex:
        lines = ["% Generated by scripts/reporting/caves_weight_sensitivity.py; do not edit.",
                 f"% roots: {' '.join(args.roots)}; draws={args.draws}; range=[{args.lo},{args.hi}]; drop_rank={args.drop_rank}"]
        for ds, d in result["datasets"].items():
            t = TEX[ds]
            lines += [
                f"\\newcommand{{\\sensPub{t}}}{{{d['published']:.3f}}}",
                f"\\newcommand{{\\sensUni{t}}}{{{d['uniform']:.3f}}}",
                f"\\newcommand{{\\sensMed{t}}}{{{d['random_median']:.3f}}}",
                f"\\newcommand{{\\sensMin{t}}}{{{d['random_min']:.3f}}}",
                f"\\newcommand{{\\sensMax{t}}}{{{d['random_max']:.3f}}}",
                f"\\newcommand{{\\sensN{t}}}{{{d['n']}}}",
                f"\\newcommand{{\\sensPct{t}}}{{{100 * d['published_percentile']:.0f}}}",
                f"\\newcommand{{\\sensPFive{t}}}{{{d['random_p05']:.3f}}}",
                f"\\newcommand{{\\sensPNfive{t}}}{{{d['random_p95']:.3f}}}",
            ]
        lines.append(f"\\newcommand{{\\sensDraws}}{{{args.draws}}}")
        args.out_tex.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
