#!/usr/bin/env python3
"""Attribute the paired ablation of Table IV to its two checks, from a replay.

The ablation of record relaxes the attitude cross-check and the inlier minimum
together, so it identifies their joint effect. forge_threshold_sweep.py can
replay the recorded signals with the inlier minimum kept at its record value
and the yaw bound opened to 180 degrees, which switches the attitude check off
and nothing else. This script turns that replay into macros: the pooled
acceptance with the attitude check alone removed, per dataset, beside the
record value the same replay reproduces.

Usage:
    python3 scripts/reporting/forge_threshold_sweep.py --cells <record cells> \
        --inliers 25 --yaw 30 180 --json-out yawoff.json
    python3 scripts/reporting/make_yawoff_macros.py yawoff.json \
        Report/Paper/aicap-2027/tables/yawoff_numbers.tex

The replay must reproduce the recorded decisions on every cell (mismatch 0);
a cell that does not is refused here as it is in the sweep.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

TAG = {"vpair": "Vpair", "uav_visloc": "Visloc", "avl": "Avl"}


def main() -> None:
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    rep = json.loads(src.read_text())
    bad = [c["cell"] for c in rep["cells"] if c["baseline_mismatch"]]
    if bad:
        raise SystemExit(f"baseline replay mismatch in {bad}")
    rec_inl = {int(c["t_inl0"]) for c in rep["cells"]}
    rec_yaw = {float(c["t_yaw0"]) for c in rep["cells"]}
    if len(rec_inl) != 1 or len(rec_yaw) != 1:
        raise SystemExit("cells disagree on the record thresholds")
    rec_inl, rec_yaw = rec_inl.pop(), rec_yaw.pop()
    agg: dict[tuple, dict] = {}
    for s in rep["sweep"]:
        if s["t_inl"] != rec_inl:
            continue
        k = (s["dataset"], float(s["t_yaw"]))
        a = agg.setdefault(k, {"acc": 0, "n": 0, "unres": 0})
        a["acc"] += s["accepted"]; a["n"] += s["n_denom"]; a["unres"] += s["unresolved"]
    lines = ["% Auto-generated by scripts/reporting/make_yawoff_macros.py - DO NOT EDIT BY HAND.",
             "% Replay of recorded signals (forge_threshold_sweep.py): inlier minimum at its record value,",
             "% yaw bound 180 deg = attitude cross-check off. Not a new run."]
    for c in rep["cells"]:
        lines.append(f"% source: {c['dir']} (baseline replay mismatches: {c['baseline_mismatch']}/{c['n']})")
    lines.append(f"\\newcommand{{\\yoInl}}{{{rec_inl}}}")
    datasets = sorted({d for d, _ in agg})
    for d in datasets:
        base = agg[(d, rec_yaw)]
        off = agg[(d, 180.0)]
        if base["unres"] or off["unres"]:
            raise SystemExit(f"unresolved frames in {d}; replay not exact")
        t = TAG[d]
        rb = 100.0 * base["acc"] / base["n"]
        ro = 100.0 * off["acc"] / off["n"]
        lines += [f"\\newcommand{{\\yoN{t}}}{{{off['n']:,}}}".replace(",", "{,}"),
                  f"\\newcommand{{\\yoRecRate{t}}}{{{rb:.1f}\\%}}",
                  f"\\newcommand{{\\yoOffRate{t}}}{{{ro:.1f}\\%}}",
                  f"\\newcommand{{\\yoOffAcc{t}}}{{{off['acc']}}}",
                  f"\\newcommand{{\\yoDiffPts{t}}}{{{ro - rb:.1f}}}"]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    print("\n".join(l for l in lines if l.startswith("\\newcommand")))


if __name__ == "__main__":
    main()
