#!/usr/bin/env python3
"""Emit bare-numeric twins of generated macros, for pgfplots coordinates.

v3_numbers.tex stores rendered values such as ``12.3\\%``. A plot
coordinate needs ``12.3``. Typing that number into a figure source would
detach it from the run that produced it. This script derives the numeric
form instead, so a rerun of gen_v3_tables.py still propagates into the
chart (the paper inputs the result as v3_numbers_numeric.tex).

Usage:
    python3 derive_slide_numbers.py <v3_numbers.tex> <out.tex>
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

SOURCE = Path(sys.argv[1])
TARGET = Path(sys.argv[2])

MACRO = re.compile(r"\\newcommand\{\\(\w+)\}\{(.*?)\}\s*$", re.MULTILINE)


def numeric_core(value: str) -> str | None:
    """'12.3\\%' -> '12.3';  '1{,}234' -> '1234';  '--' -> None."""
    stripped = re.sub(r"\\[%,&]|\{|\}|\\,|~|\\ |\s", "", value)
    stripped = stripped.replace(",", "")
    match = re.fullmatch(r"-?\d+(?:\.\d+)?", stripped)
    return match.group(0) if match else None


def main() -> int:
    lines = [
        "% Auto-generated by derive_slide_numbers.py from v3_numbers.tex",
        "% DO NOT EDIT. Numeric twins of the generated macros, for plot coordinates.",
    ]
    kept = 0
    for name, value in MACRO.findall(SOURCE.read_text(encoding="utf-8")):
        core = numeric_core(value)
        if core is None:
            continue
        lines.append(f"\\newcommand{{\\num{name}}}{{{core}}}")
        kept += 1
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TARGET}: {kept} macros")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
