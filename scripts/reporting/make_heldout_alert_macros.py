#!/usr/bin/env python3
"""Rescore the accepted forced fixes of the pre-registered held-out campaigns
at alert limits other than the benchmark radius R.

Sec. III-A says R is a benchmark label, not an alert limit, and that an
operator can rescore at their own limit. This script does that rescoring on
the held-out records (E1 UAV-VisLoc, E1b VPAIR): for every accepted trial whose
forced reference is wrong, it reads the published position error after fusion
and counts how many exceed each limit. No new run, no new label: the trials
are exactly the Misl. trials of Table II.

Usage:
    python3 scripts/reporting/make_heldout_alert_macros.py \
        --visloc results_server/v4_2026-10-24/results/v4_e1_heldout_visloc \
        --vpair  results_server/v4_2026-10-24/results/v4_e1b_heldout_vpair \
        --out Report/Paper/aicap-2027/tables/heldout_alert_numbers.tex

Cells are the injection directories of each campaign root (clean cells are
skipped); each predictions.csv is named in a % source line with its SHA-256.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import statistics
from pathlib import Path

LIMITS_M = (500, 1000, 2000)
KEYS = {"visloc": "Visloc", "vpair": "Vpair"}


def accepted_wrong(csv_path: Path) -> list[float]:
    with csv_path.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    out = []
    for r in rows:
        if r.get("adversarial_attacked") not in ("True", "1", "true"):
            continue
        if r.get("accepted_for_metrics") != "True":
            continue
        if r.get("is_wrong_reference") not in ("True", "1"):
            continue
        out.append(float(r["post_fgo_error_m"]))
    return out


def cells(root: Path) -> list[Path]:
    found = sorted(p for p in root.rglob("predictions.csv") if "clean" not in str(p.relative_to(root)))
    if not found:
        raise SystemExit(f"no injection cells under {root}")
    return found


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--visloc", required=True, type=Path)
    ap.add_argument("--vpair", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()

    lines = ["% Auto-generated by scripts/reporting/make_heldout_alert_macros.py - DO NOT EDIT BY HAND.",
             "% Accepted wrong-reference trials of the held-out campaigns, rescored at alert limits."]
    macros = ["\\newcommand{\\haLimFiveM}{500}", "\\newcommand{\\haLimOneKKm}{1}", "\\newcommand{\\haLimTwoKKm}{2}"]
    for ds, root in (("visloc", a.visloc), ("vpair", a.vpair)):
        key = KEYS[ds]
        errs: list[float] = []
        for p in cells(root):
            e = accepted_wrong(p)
            errs += e
            digest = hashlib.sha256(p.read_bytes()).hexdigest()[:16]
            lines.append(f"% source: {p} sha256:{digest} accepted_wrong={len(e)}")
        errs.sort()
        n = len(errs)
        macros.append(f"\\newcommand{{\\ha{key}N}}{{{n}}}")
        macros.append(f"\\newcommand{{\\ha{key}MinErr}}{{{errs[0]:.0f}}}")
        macros.append(f"\\newcommand{{\\ha{key}MedErr}}{{{statistics.median(errs):.0f}}}")
        for lim in LIMITS_M:
            k = sum(e > lim for e in errs)
            tag = {500: "Five", 1000: "OneK", 2000: "TwoK"}[lim]
            macros.append(f"\\newcommand{{\\ha{key}Over{tag}}}{{{k}}}")
            macros.append(f"\\newcommand{{\\ha{key}Over{tag}Pct}}{{{100.0 * k / n:.0f}\\%}}")
    a.out.write_text("\n".join(lines + macros) + "\n", encoding="utf-8")
    print(f"wrote {a.out}")
    print("\n".join(macros))


if __name__ == "__main__":
    main()
