#!/usr/bin/env python3
"""Macros for E2b (held-out repeats) and E6 (fusion and injection density).

Reads the JSON of experiments/analysis/repeat_agreement.py (one file per
dataset, run 0 = the held-out run of record) and of
experiments/analysis/e6_fusion_analysis.py.

Usage: make_e2b_e6_macros.py OUT.tex --e6 E6.json --vpair E2B_VPAIR.json
           [--visloc E2B_VISLOC_F09.json]
"""
import argparse
import hashlib
import json
from pathlib import Path


def pct(x):
    return f"{100.0 * x:.1f}\\%"


def pts(x):
    return f"{100.0 * x:+.1f}".replace("-", "$-$")


def ci(c):
    return f"[{pts(c[0])}, {pts(c[1])}]"


def src(p):
    return f"% source: {Path(p).name} sha256:{hashlib.sha256(Path(p).read_bytes()).hexdigest()[:16]}"


def repeat_macros(prefix, p):
    o = json.load(open(p))
    runs = o["runs"]
    rates = [o["per_run"][n]["frame_rate"] for n in runs]
    acc = sum(o["per_run"][n]["accepted_trials"] for n in runs)
    mis = sum(o["per_run"][n]["misleading_trials"] for n in runs)
    unk = sum(o["per_run"][n]["unknown_error_trials"] for n in runs)
    return [src(p),
            f"\\newcommand{{\\{prefix}Runs}}{{{len(runs)}}}",
            f"\\newcommand{{\\{prefix}Frames}}{{{o['attacked_frames']:,}}}".replace(",", "{,}"),
            f"\\newcommand{{\\{prefix}RateRecord}}{{{pct(rates[0])}}}",
            f"\\newcommand{{\\{prefix}RateRepeats}}{{{', '.join(pct(r) for r in rates[1:])}}}",
            f"\\newcommand{{\\{prefix}RateLo}}{{{pct(min(rates))}}}",
            f"\\newcommand{{\\{prefix}RateHi}}{{{pct(max(rates))}}}",
            f"\\newcommand{{\\{prefix}Kappa}}{{{o['fleiss_kappa']:.2f}}}",
            f"\\newcommand{{\\{prefix}Jaccard}}{{{o['jaccard_mean']:.2f}}}",
            f"\\newcommand{{\\{prefix}All}}{{{o['accepted_in_all']}}}",
            f"\\newcommand{{\\{prefix}Any}}{{{o['accepted_in_any']}}}",
            f"\\newcommand{{\\{prefix}AnyRate}}{{{pct(o['accepted_in_any'] / o['attacked_frames'])}}}",
            f"\\newcommand{{\\{prefix}AccTrials}}{{{acc}}}",
            f"\\newcommand{{\\{prefix}MisTrials}}{{{mis}}}",
            f"\\newcommand{{\\{prefix}UnknownTrials}}{{{unk}}}"]


def e6_macros(p):
    o = json.load(open(p))
    d, f = o["density"], o["fusion"]
    dp, fp = d["paired"]["accepted"], f["paired"]["accepted"]
    rd = o["dense_repeats"][0]
    rdd, rdf = rd["on_density_trials"]["accepted"], rd["on_fusion_trials"]["accepted"]
    e, cov = f["errors"], f["clean_coverage"]
    mis = d["sparse"]["misleading"] + f["nofgo"]["misleading"]
    acc = d["sparse"]["accepted"] + f["nofgo"]["accepted"]
    return [src(p),
            f"\\newcommand{{\\eSixSparseFrames}}{{{d['paired']['frames']}}}",
            f"\\newcommand{{\\eSixSparseRate}}{{{pct(dp['rate_a'])}}}",
            f"\\newcommand{{\\eSixDenseRate}}{{{pct(dp['rate_b'])}}}",
            f"\\newcommand{{\\eSixDensityDiff}}{{{pts(dp['diff'])}}}",
            f"\\newcommand{{\\eSixDensityCI}}{{{ci(dp['diff_ci'])}}}",
            f"\\newcommand{{\\eSixDensityRepDiff}}{{{pts(rdd['diff'])}}}",
            f"\\newcommand{{\\eSixDensityRepCI}}{{{ci(rdd['diff_ci'])}}}",
            f"\\newcommand{{\\eSixFusionFrames}}{{{f['paired']['frames']:,}}}".replace(",", "{,}"),
            f"\\newcommand{{\\eSixNofgoRate}}{{{pct(fp['rate_a'])}}}",
            f"\\newcommand{{\\eSixFgoRate}}{{{pct(fp['rate_b'])}}}",
            f"\\newcommand{{\\eSixFusionDiff}}{{{pts(fp['diff'])}}}",
            f"\\newcommand{{\\eSixFusionCI}}{{{ci(fp['diff_ci'])}}}",
            f"\\newcommand{{\\eSixFusionDisc}}{{{fp['a_only'] + fp['b_only']}}}",
            f"\\newcommand{{\\eSixFusionRepDiff}}{{{pts(rdf['diff'])}}}",
            f"\\newcommand{{\\eSixFusionRepCI}}{{{ci(rdf['diff_ci'])}}}",
            f"\\newcommand{{\\eSixFusionRepDisc}}{{{rdf['a_only'] + rdf['b_only']}}}",
            f"\\newcommand{{\\eSixMisTrials}}{{{mis}}}",
            f"\\newcommand{{\\eSixAccTrials}}{{{acc}}}",
            f"\\newcommand{{\\eSixPrePostMedian}}{{{e['dense_median_post_minus_pre_m']:.0f}}}",
            f"\\newcommand{{\\eSixPostBelowPre}}{{{pct(e['dense_share_post_below_pre'])}}}",
            f"\\newcommand{{\\eSixCovFgo}}{{{pct(cov['fgo'])}}}",
            f"\\newcommand{{\\eSixCovNofgo}}{{{pct(cov['nofgo'])}}}"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--e6", required=True); ap.add_argument("--vpair", required=True)
    ap.add_argument("--visloc")
    a = ap.parse_args()
    lines = ["% Auto-generated by scripts/reporting/make_e2b_e6_macros.py - DO NOT EDIT BY HAND."]
    lines += repeat_macros("eTwoBVpair", a.vpair)
    if a.visloc:
        lines += repeat_macros("eTwoBVisloc", a.visloc)
    lines += e6_macros(a.e6)
    Path(a.out).write_text("\n".join(lines) + "\n")
    print("\n".join(l for l in lines if not l.startswith("%")))


if __name__ == "__main__":
    main()
